"""Shared fixtures for the real-time clipper tests.

``synthetic_video``    the 60 s fixture video (design section 9), generated by
                       FFmpeg once and cached in pytest's cache directory
                       across runs (``pytest --cache-clear`` regenerates it).
``synthetic_segments`` that video split into 2 s MPEG-TS segments, once per
                       session. The files are SHARED: do not hand them to
                       anything that deletes or modifies files (such as
                       SegmentBuffer); use ``fresh_synthetic_segments``.
``fresh_synthetic_segments``  a per-test copy of ``synthetic_segments`` in
                       ``tmp_path``, safe to delete.
"""

from __future__ import annotations

import hashlib
import shutil
import uuid
from pathlib import Path
from typing import List

import pytest

from VidFlow.realtime.testing import (
    SYNTHETIC_BURSTS,
    SYNTHETIC_DURATION,
    copy_segments,
    make_synthetic_video,
    segments_from_file,
)
from VidFlow.realtime.types import Segment

# Bump when make_synthetic_video's output changes, to invalidate cached copies.
_FIXTURE_VERSION = "1"
SYNTHETIC_CHANNEL = "test"


def pytest_configure(config: pytest.Config) -> None:
    # Also registered in pyproject.toml; repeated so the marker is known even
    # if pytest is run with a different rootdir/config.
    config.addinivalue_line("markers", "slow: paced in real time or otherwise long-running")


def _require_ffmpeg() -> None:
    if shutil.which("ffmpeg") is None or shutil.which("ffprobe") is None:
        pytest.skip("ffmpeg and ffprobe must be on PATH")


@pytest.fixture(scope="session")
def synthetic_video(request: pytest.FixtureRequest, tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Path to the 60 s, 320x180, 30 fps fixture with loud bursts at (10, 16) and (40, 46)."""
    _require_ffmpeg()
    key = hashlib.sha1(
        f"{_FIXTURE_VERSION}|{SYNTHETIC_DURATION}|{SYNTHETIC_BURSTS}".encode()
    ).hexdigest()[:12]
    name = f"synthetic_{key}.mp4"
    cache = getattr(request.config, "cache", None)
    cache_dir = Path(cache.mkdir("vidflow-realtime")) if cache is not None else tmp_path_factory.mktemp("video")
    path = cache_dir / name
    if not path.is_file() or path.stat().st_size == 0:
        # make_synthetic_video writes to a temporary name and renames, so a
        # concurrent run never sees a half-written file.
        make_synthetic_video(path)
    return path


@pytest.fixture(scope="session")
def synthetic_segments(synthetic_video: Path, tmp_path_factory: pytest.TempPathFactory) -> List[Segment]:
    """``synthetic_video`` split into 2 s segments (shared, read-only)."""
    out_dir = tmp_path_factory.mktemp("synthetic_segments")
    return segments_from_file(synthetic_video, out_dir, channel=SYNTHETIC_CHANNEL, segment_time=2.0)


@pytest.fixture
def fresh_synthetic_segments(synthetic_segments: List[Segment], tmp_path: Path) -> List[Segment]:
    """A private copy of ``synthetic_segments`` that the test may delete or modify."""
    return copy_segments(synthetic_segments, tmp_path / f"segments_{uuid.uuid4().hex[:8]}")
